/**
 * Privacy primitives — design doc §4.1 and §7.3.
 *
 * Two rules govern everything in this codebase:
 *  1. The central database never sees a raw identity. Every data source —
 *     a CBO's enrollment sheet or a state outcome export — turns the shared
 *     identifier (the CDCR number) into a keyed hash before upload, so the
 *     two halves of the evidence can be joined without either side's raw IDs.
 *  2. Small groups are never reported. Any aggregate over fewer than
 *     SMALL_CELL_THRESHOLD people is replaced with "<10" so no individual
 *     can be re-identified from a published breakdown.
 */
import { createHmac } from "node:crypto";
import { DEMO_NETWORK_KEY, normalizeCdcrNumber } from "./normalize";

export { DEMO_NETWORK_KEY, normalizeCdcrNumber };

/**
 * participant_key = HMAC-SHA256(network_key, normalized CDCR number), hex (§4.1 v1.6).
 *
 * Why a shared identifier: outcome systems (CDCR, parole, courts) never see
 * an organization's local IDs, so a key derived from org-local IDs could
 * never be matched to outcomes. The CDCR number is the identifier both
 * halves already record.
 *
 * Why keyed (HMAC) rather than a plain hash: CDCR numbers are short and
 * fixed-format, so a plain SHA-256 could be reversed by enumerating every
 * possible number. Without the network key the hash cannot be recomputed.
 * The key is held by TPW (as the network's data steward) and given only to
 * the hashing tool each data source runs locally; it is never stored in the
 * central database. Rotating it requires re-hashing every source.
 *
 * Note: the M0 demo CSVs carry 16-hex-char keys pre-generated by the Python
 * generator. This function is the form real deployments use.
 */
export function participantKey(cdcrNumber: string, networkKey: string): string {
  if (networkKey.length === 0) throw new Error("participantKey: network key is required");
  return createHmac("sha256", networkKey).update(normalizeCdcrNumber(cdcrNumber), "utf8").digest("hex");
}

/** Groups smaller than this are suppressed (§4.1 / §7.3). */
export const SMALL_CELL_THRESHOLD = 10;

export const SUPPRESSED = "<10" as const;

export type SuppressedValue = number | typeof SUPPRESSED;

export interface GroupRow {
  label: string;
  n: number;
  value: number | null;
}

export interface SuppressedGroupRow {
  label: string;
  n: SuppressedValue;
  value: SuppressedValue | null;
}

/** Suppress a single value when its group is below the threshold. */
export function suppressValue(n: number, value: number | null): SuppressedValue | null {
  if (n < SMALL_CELL_THRESHOLD) return SUPPRESSED;
  return value;
}

/**
 * Apply small-cell suppression to a set of group aggregates (§7.3):
 * rows with n < 10 have both their count and value replaced with "<10"
 * and must not be charted or included in reports.
 */
export function suppressSmallCells(rows: GroupRow[]): SuppressedGroupRow[] {
  return rows.map((row) =>
    row.n < SMALL_CELL_THRESHOLD
      ? { label: row.label, n: SUPPRESSED, value: SUPPRESSED }
      : { label: row.label, n: row.n, value: row.value },
  );
}
